import { test, expect } from '@playwright/test'
import path from 'node:path'

test('real camera API with synthetic device: calibrate, auto capture, review, edit, export, stop', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('Local system online')).toBeVisible()
  await page.getByRole('button', { name: 'New session', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'New lecture session' })
  await dialog.getByLabel('Lecture title').fill(`Browser verification ${Date.now()}`)
  await dialog.getByLabel('Course').fill('Computer Vision · Synthetic camera')
  await dialog.getByRole('button', { name: 'Create session' }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Start camera', exact: true }).click()
  await expect(page.getByText('CAMERA LIVE', { exact: true })).toBeVisible({ timeout: 30_000 })
  await page.getByRole('button', { name: 'Calibrate board', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Board corner 1' })).toBeVisible()
  await page.getByRole('button', { name: 'Confirm board', exact: true }).click()
  await expect(page.getByText('Whiteboard calibrated', { exact: true })).toBeVisible()
  await expect(page.locator('.capture-card')).toHaveCount(1, { timeout: 45_000 })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/workspace-desktop.png', fullPage: true })
  await page.waitForTimeout(3500)
  await expect(page.locator('.capture-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Capture now' }).click()
  await expect(page.locator('.capture-card')).toHaveCount(2)
  await page.getByRole('button', { name: 'Stop', exact: true }).click()
  await expect(page.getByText('Camera access only when you choose.')).toBeVisible()
  await page.locator('.capture-card').first().click()
  const capture = page.getByRole('dialog', { name: 'Capture details' })
  await capture.getByLabel('Capture name').fill('Reviewed equation')
  await capture.getByLabel('Your notes').fill('Actual persisted browser-test note.')
  await capture.getByRole('button', { name: 'Save changes' }).click()
  await expect(capture.getByRole('heading', { name: 'Reviewed equation' })).toBeVisible()
  await capture.getByRole('button', { name: 'Enhanced', exact: true }).click()
  await capture.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await expect(capture.getByText('125%')).toBeVisible()
  await capture.getByRole('button', { name: 'Close capture details' }).click()
  await page.getByRole('button', { name: 'Export notes' }).click()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Lecture PDF', exact: true }).click()
  expect((await downloaded).suggestedFilename()).toMatch(/\.pdf$/)
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Stability duration' }).fill('2.5')
  await page.getByRole('button', { name: 'Apply settings' }).click()
  await expect(page.getByText('Settings applied to the analysis pipeline.')).toBeVisible()
  await page.reload()
  await expect(page.locator('.capture-card')).toHaveCount(2)
  await page.getByRole('button', { name: /^Saved notes/ }).click()
  await page.getByRole('textbox', { name: 'Search captures' }).fill('persisted browser-test')
  await expect(page.locator('.capture-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Switch to dark mode' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  await page.getByRole('button', { name: 'Start camera', exact: true }).click()
  await expect(page.getByText('CAMERA LIVE', { exact: true })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/workspace-dark.png', fullPage: true })
  await page.locator('video').evaluate((element: HTMLVideoElement) => (element.srcObject as MediaStream).getVideoTracks()[0].dispatchEvent(new Event('ended')))
  await expect(page.getByText('Camera access only when you choose.')).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('Camera disconnected')
  expect(errors).toEqual([])
})

test('upload, calibrate and process the real synthetic video; tablet layout stays usable', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'New session', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'New lecture session' })
  await dialog.getByLabel('Lecture title').fill(`Replay verification ${Date.now()}`)
  await dialog.getByRole('button', { name: 'Create session' }).click()
  await page.getByRole('button', { name: 'Video replay', exact: true }).click()
  await page.getByLabel('Upload lecture video').setInputFiles(path.resolve('../data/demo/synthetic-lecture.avi'))
  await expect(page.getByRole('button', { name: 'Confirm board', exact: true })).toBeVisible({ timeout: 30_000 })
  // Detection is an OpenCV proposal, followed by an explicit human confirmation.
  await page.getByRole('button', { name: 'Calibrate board', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm board', exact: true }).click()
  await page.getByRole('button', { name: 'Start replay', exact: true }).click()
  await expect(page.getByText('REPLAY · COMPLETED', { exact: true })).toBeVisible({ timeout: 75_000 })
  expect(await page.locator('.capture-card').count()).toBeGreaterThanOrEqual(3)
  await page.setViewportSize({ width: 834, height: 1112 })
  await page.screenshot({ path: 'test-results/workspace-tablet.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const manualResponse = page.waitForResponse(response => response.url().endsWith('/manual') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Capture now' }).click()
  const manualResult = await (await manualResponse).json()
  if (manualResult.decision === 'confirm') {
    const warning = page.getByRole('dialog', { name: 'Review manual capture' })
    await expect(warning).toBeVisible()
    await warning.getByRole('button', { name: 'Save anyway' }).click()
    await expect(warning).not.toBeVisible()
  }
  await expect(page.getByRole('status')).toContainText('captured')
})

